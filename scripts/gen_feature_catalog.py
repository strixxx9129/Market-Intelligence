"""Generate docs/feature-catalog.md from the feature registry.

    python scripts/gen_feature_catalog.py           # (re)write the catalog
    python scripts/gen_feature_catalog.py --check   # exit 1 if the catalog is out of date (CI)

Run via `make feature-catalog`. The catalog is generated, so it can never drift from the code:
CI fails a PR that adds or changes a feature without regenerating it.
"""

import argparse
import inspect
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CATALOG = REPO_ROOT / "docs" / "feature-catalog.md"
# Import the CURRENT source tree, not a possibly stale installed copy.
sys.path.insert(0, str(REPO_ROOT / "backend" / "src"))

from marketlens.features import FEATURES  # noqa: E402
from marketlens.features.builder import code_hash, resolve_set, set_definition  # noqa: E402
from marketlens.features.sets import FEATURE_SETS  # noqa: E402


def render() -> str:
    lines = [
        "# Feature catalog",
        "",
        "<!-- GENERATED by scripts/gen_feature_catalog.py from the feature registry. "
        "Do not edit by hand: run `make feature-catalog`. -->",
        "",
        "Every feature uses only candles up to and including day *t* (its close is known at the",
        "end of day *t*). `lookback` = earlier rows needed; the first `lookback` rows are",
        "warm-up and are dropped by the builder, never filled. Every feature passes the",
        "truncation test (`backend/tests/unit/test_feature_leakage.py`).",
        "",
        "## Feature sets",
        "",
        "| version | features | warm-up rows | code hash |",
        "|---|---|---|---|",
    ]
    for version in sorted(FEATURE_SETS):
        specs = resolve_set(version)
        definition = set_definition(version, specs)
        lines.append(
            f"| `{version}` | {len(specs)} | {definition['warmup_rows']} "
            f"| `{code_hash(definition, specs)[:12]}` |"
        )

    for family in sorted({s.family for s in FEATURES.values()}):
        specs = sorted((s for s in FEATURES.values() if s.family == family), key=lambda s: s.name)
        module = inspect.getmodule(specs[0].func)
        doc = inspect.cleandoc(module.__doc__ or "") if module else ""
        rel = Path(inspect.getsourcefile(specs[0].func) or "").resolve().relative_to(REPO_ROOT)
        lines += ["", f"## {family}", "", f"Source: [`{rel.as_posix()}`](../{rel.as_posix()})", ""]
        if doc:
            lines += [doc, ""]
        lines += ["| feature | lookback | in sets | description |", "|---|---|---|---|"]
        for s in specs:
            sets = ", ".join(v for v, names in sorted(FEATURE_SETS.items()) if s.name in names)
            lines.append(f"| `{s.name}` | {s.lookback} | {sets or '-'} | {s.description} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the catalog is stale")
    args = parser.parse_args()

    content = render()
    if args.check:
        current = CATALOG.read_text(encoding="utf-8") if CATALOG.exists() else ""
        if current != content:
            print(f"{CATALOG.relative_to(REPO_ROOT)} is out of date: run `make feature-catalog`")
            return 1
        print("feature catalog is up to date")
        return 0
    CATALOG.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {CATALOG.relative_to(REPO_ROOT)} ({len(FEATURES)} features)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
